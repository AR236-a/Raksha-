// Haversine Distance Formula (km)
export function calculateHaversineDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Number((R * c).toFixed(1));
}

// Predict police station and sorted stations from latitude/longitude
export function predictPoliceStationFromCoords(
  latitude: number,
  longitude: number,
  source: LocationPredictionResult['source'] = 'Live Device GPS',
  accuracyMeters: number = 15,
  customLocationName?: string,
  stateHint?: string,
  districtHint?: string
): LocationPredictionResult {
  const allStationsSorted = allIndiaPoliceStations
    .map((station) => {
      const distanceKm = calculateHaversineDistanceKm(
        latitude,
        longitude,
        station.lat,
        station.lng
      );
      return { ...station, distanceKm };
    })
    .sort((a, b) => a.distanceKm - b.distanceKm);

  const nearest = allStationsSorted[0];
  const detectedLocationName =
    customLocationName ||
    `${nearest.district}, ${nearest.state} (near ${nearest.name})`;

  return {
    latitude,
    longitude,
    accuracyMeters,
    detectedLocationName,
    district: districtHint || nearest.district,
    state: stateHint || nearest.state,
    pincode: nearest.pincode,
    country: 'India (Bharat)',
    source,
    nearestStation: nearest,
    allStationsSorted,
    isAccurate: accuracyMeters <= 100,
    diagnostics: `Geodetic Match: ${nearest.name} is ${nearest.distanceKm} km away. Source: ${source}. Traffic Status: ${nearest.trafficStatus || 'Normal'}.`,
  };
}

// Predict from 6-digit Indian PIN code or prefix
export function predictLocationByPincode(
  pincode: string
): LocationPredictionResult | null {
  const cleanPin = pincode.replace(/\D/g, '').trim();
  if (cleanPin.length < 2) return null;

  // Exact 6-digit PIN match
  if (cleanPin.length === 6) {
    const exactStation = allIndiaPoliceStations.find(
      (s) => s.pincode === cleanPin
    );
    if (exactStation) {
      return predictPoliceStationFromCoords(
        exactStation.lat,
        exactStation.lng,
        'PIN Code Predictor',
        25,
        `${exactStation.district}, ${exactStation.state} (PIN: ${cleanPin})`,
        exactStation.state,
        exactStation.district
      );
    }
  }

  // 3-digit or 2-digit prefix match
  const prefix3 = cleanPin.substring(0, 3);
  const prefix2 = cleanPin.substring(0, 2);

  const matchedZone =
    allIndiaPinZones.find((z) => z.pincodePrefix === prefix3) ||
    allIndiaPinZones.find((z) => z.pincodePrefix === prefix2);

  if (matchedZone) {
    return predictPoliceStationFromCoords(
      matchedZone.lat,
      matchedZone.lng,
      'PIN Code Predictor',
      1000,
      `${matchedZone.city}, ${matchedZone.state} (Postal Zone ${cleanPin})`,
      matchedZone.state,
      matchedZone.district
    );
  }

  return null;
}

// Predict by city or district text search
export function predictLocationByDistrictOrCity(
  query: string
): LocationPredictionResult | null {
  const q = query.toLowerCase().trim();
  if (!q) return null;

  const foundStation = allIndiaPoliceStations.find(
    (s) =>
      s.city.toLowerCase().includes(q) ||
      s.district.toLowerCase().includes(q) ||
      s.state.toLowerCase().includes(q) ||
      s.name.toLowerCase().includes(q)
  );

  if (foundStation) {
    return predictPoliceStationFromCoords(
      foundStation.lat,
      foundStation.lng,
      'District Quick Select',
      50,
      `${foundStation.city}, ${foundStation.state}`,
      foundStation.state,
      foundStation.district
    );
  }

  return null;
}

// Reverse Geocoding with reliable graceful fallback
export async function reverseGeocodeCoords(
  lat: number,
  lng: number
): Promise<{
  address: string;
  city?: string;
  state?: string;
  district?: string;
  pincode?: string;
}> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2500);

    const res = await fetch(
      `https://nominatim.openstreetmap.org/reverse?format=jsonv2&lat=${lat}&lon=${lng}`,
      {
        signal: controller.signal,
        headers: {
          Accept: 'application/json',
        },
      }
    );
    clearTimeout(timeoutId);

    if (res.ok) {
      const data = await res.json();
      const addr = data.address || {};
      return {
        address: data.display_name || `${lat.toFixed(4)}°N, ${lng.toFixed(4)}°E`,
        city: addr.city || addr.town || addr.village || addr.suburb || addr.county,
        district: addr.state_district || addr.district || addr.county,
        state: addr.state,
        pincode: addr.postcode,
      };
    }
  } catch (err) {
    console.debug('Reverse geocode offline/fallback:', err);
  }

  return {
    address: `GPS Coordinates: ${lat.toFixed(4)}°N, ${lng.toFixed(4)}°E`,
  };
}

// Public IP / Network Location Predictor (Fallback when device GPS is denied/blocked)
export async function predictLocationFromIP(): Promise<LocationPredictionResult> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2500);

    const res = await fetch('https://ipapi.co/json/', { signal: controller.signal });
    clearTimeout(timeoutId);

    if (res.ok) {
      const data = await res.json();
      if (data.latitude && data.longitude) {
        return predictPoliceStationFromCoords(
          data.latitude,
          data.longitude,
          'IP Geolocation',
          data.accuracy || 2000,
          `${data.city || 'Metro'}, ${data.region || data.country_name || 'India'}`,
          data.region,
          data.city
        );
      }
    }
  } catch (e) {
    console.debug('IP Geolocation fallback to National Capital Region:', e);
  }

  // Ultimate fallback to New Delhi Connaught Place
  return predictPoliceStationFromCoords(
    28.6315,
    77.2167,
    'Fallback Metro',
    50,
    'Connaught Place, New Delhi (National Reference)',
    'Delhi',
    'New Delhi District'
  );
}
